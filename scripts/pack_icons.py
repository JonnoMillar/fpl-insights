#!/usr/bin/env python3
"""Pack the generated icon set into one small sprite for the dashboard.

The delivered artwork (docs/brand-handoff/transparent-suite) is four large
transparent PNG atlases, 3.2 MB in all, for icons that are never drawn above
40px. This crops each icon from its atlas cell, keeps only its own strokes
(neighbouring artwork that spills over a cell edge is dropped), squares it
with even padding and writes 96px alpha cells into one sheet:

    assets/icons.png   the sheet, about 90 KB
    assets/icons.css   .ico plus one modifier class per icon

dashboard.py embeds the sheet as a data URI, so the page stays
self-contained and works from file:// (CSS masks load in CORS mode, which a
local file cannot satisfy). The drawings themselves are never redrawn.

Needs Pillow and numpy, which the build itself does not: run it only when
the artwork changes.

    python scripts/pack_icons.py
"""

import json
from collections import deque
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "docs" / "brand-handoff" / "transparent-suite"
OUT = ROOT / "assets"
CELL = 96
COLS = 8
PAD = 0.06          # share of the cell left clear on each side
SPILL = 0.04        # components below this share of the icon's ink are spill


def components(mask):
    """Connected components of a boolean array, as lists of (y, x)."""
    seen = np.zeros_like(mask, dtype=bool)
    h, w = mask.shape
    for y0, x0 in zip(*np.nonzero(mask)):
        if seen[y0, x0]:
            continue
        comp, queue = [], deque([(y0, x0)])
        seen[y0, x0] = True
        while queue:
            y, x = queue.popleft()
            comp.append((y, x))
            for ny, nx in ((y + 1, x), (y - 1, x), (y, x + 1), (y, x - 1)):
                if 0 <= ny < h and 0 <= nx < w and mask[ny, nx] and not seen[ny, nx]:
                    seen[ny, nx] = True
                    queue.append((ny, nx))
        yield comp


def icon_alpha(atlas, entry):
    """The icon's own alpha, squared and padded, at CELL px."""
    x0, y0, x1, y1 = entry["cell"]
    alpha = np.asarray(atlas.crop((x0, y0, x1, y1)).getchannel("A"))
    ink = alpha > 40
    comps = list(components(ink))
    total = sum(len(c) for c in comps)
    h, w = ink.shape
    keep = np.zeros_like(ink)
    for comp in comps:
        ys, xs = zip(*comp)
        touches_edge = min(xs) == 0 or min(ys) == 0 or max(xs) == w - 1 or max(ys) == h - 1
        # Spill from a neighbouring drawing touches the cell edge and is
        # small; a speck of noise is small anywhere.
        if len(comp) < SPILL * total and (touches_edge or len(comp) < 0.002 * total):
            continue
        keep[ys, xs] = True
    ys, xs = np.nonzero(keep)
    top, bottom, left, right = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1
    side = max(bottom - top, right - left)
    side = int(round(side / (1 - 2 * PAD)))
    cy, cx = (top + bottom) / 2, (left + right) / 2
    # Zero alpha outside the kept components, then crop a centred square.
    clean = np.where(_near(keep), alpha, 0).astype(np.uint8)
    img = Image.fromarray(clean, "L")
    box = (int(round(cx - side / 2)), int(round(cy - side / 2)))
    sq = Image.new("L", (side, side), 0)
    sq.paste(img, (-box[0], -box[1]))
    return sq.resize((CELL, CELL), Image.LANCZOS)


def _near(keep):
    """Kept ink grown by two pixels, so anti-aliased edges survive."""
    grown = keep.copy()
    for _ in range(2):
        g = grown.copy()
        g[1:] |= grown[:-1]; g[:-1] |= grown[1:]
        g[:, 1:] |= grown[:, :-1]; g[:, :-1] |= grown[:, 1:]
        grown = g
    return grown


def main():
    catalog = json.loads((SRC / "catalog.json").read_text(encoding="utf-8"))["icons"]
    rows = -(-len(catalog) // COLS)
    sheet = Image.new("LA", (CELL * COLS, CELL * rows), (0, 0))
    atlases = {}
    css = [
        "/* Generated by scripts/pack_icons.py from the generated icon set. */",
        ".ico{display:inline-block;flex:none;width:var(--ico,24px);height:var(--ico,24px);"
        "background-color:currentColor;vertical-align:middle;"
        "-webkit-mask-image:var(--ico-sheet);mask-image:var(--ico-sheet);"
        "-webkit-mask-repeat:no-repeat;mask-repeat:no-repeat;"
        f"-webkit-mask-size:{COLS * 100}% {rows * 100}%;mask-size:{COLS * 100}% {rows * 100}%}}",
        "@media (forced-colors:active){.ico{background-color:CanvasText}}",
    ]
    for i, entry in enumerate(catalog):
        name = entry["atlas"]
        if name not in atlases:
            atlases[name] = Image.open(SRC / name).convert("RGBA")
        a = icon_alpha(atlases[name], entry)
        col, row = i % COLS, i // COLS
        cell = Image.merge("LA", [Image.new("L", (CELL, CELL), 0), a])
        sheet.paste(cell, (col * CELL, row * CELL))
        px = col * 100 / (COLS - 1)
        py = row * 100 / (rows - 1)
        pos = f"{px:.4g}% {py:.4g}%"
        css.append(f".ico-{entry['name']}{{-webkit-mask-position:{pos};mask-position:{pos}}}")
    OUT.mkdir(exist_ok=True)
    sheet.save(OUT / "icons.png", optimize=True)
    (OUT / "icons.css").write_text("\n".join(css) + "\n", encoding="utf-8")
    print(f"wrote {OUT / 'icons.png'} ({(OUT / 'icons.png').stat().st_size // 1024} KB), "
          f"{len(catalog)} icons")


if __name__ == "__main__":
    main()
